"""Какие эксперименты запускаем. Это единственный файл, который нужно править, чтобы «крутить» гиперпараметры.

Схема «один параметр за раз» (one-at-a-time): каждая серия (group) меняет ОДИН гиперпараметр,
остальные остаются по умолчанию. Так эффект параметра виден в чистом виде.

Формат: SWEEPS[алгоритм][серия] = список словарей «что переопределить».
Ключи — имена параметров SB3 (learning_rate, clip_range ...) либо полей ExperimentConfig
(n_envs, net_arch, activation).
"""
from __future__ import annotations

# Общие настройки: ОДИНАКОВЫЕ для PPO и A2C, чтобы сравнение было честным.
# Бюджет выбран по базовому запуску: PPO с дефолтами выходит на максимум (500) примерно за 25-30 тысяч шагов,
# поэтому 100 тысяч шагов — это 70% «плато», на котором различий не видно. 50 тысяч оставляют место и для
# медленных конфигураций (они не успеют — это и есть результат), и для проверки срывов после выхода на плато.
# Вернуть прежний бюджет: total_timesteps=100_000, eval_freq=5_000.
COMMON = dict(
    total_timesteps=50_000,   # бюджет в шагах среды
    eval_freq=2_500,          # как часто оцениваем политику (20 точек на кривой)
    n_eval_episodes=10,
)


# Настройки по средам. CartPole: 50 000 шагов (см. комментарий выше). Acrobot-v1 учится дольше: ориентир 100 000 шагов
# (проверь на серии baseline: `python -m src.sweep --env Acrobot-v1 --groups baseline`).
ENV_COMMON = {
    "CartPole-v1": COMMON,
    "Acrobot-v1": dict(total_timesteps=100_000, eval_freq=5_000, n_eval_episodes=10),
}


def values(param: str, vals: list) -> list[dict]:
    return [{param: v} for v in vals]


def grid(param1: str, vals1: list, param2: str, vals2: list) -> list[dict]:
    """Сетка из двух параметров: все пары значений. Порядок: строки — param1, столбцы — param2."""
    return [{param1: a, param2: b} for a in vals1 for b in vals2]


